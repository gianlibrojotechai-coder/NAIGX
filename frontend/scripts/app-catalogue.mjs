/**
 * Generates the n8n app catalogue — every integration n8n ships — from the
 * published `n8n-nodes-base` package (D-94, D-96), into two files:
 *
 *   frontend/src/app-catalogue.ts            what the app picker offers
 *   backend/src/nie/n8n-node-catalogue.ts    what the n8n scaffold maps against
 *
 *   node scripts/app-catalogue.mjs            # latest published version
 *   node scripts/app-catalogue.mjs 2.15.1     # a pinned version
 *
 * Generated from n8n's own node files rather than typed by hand: each node's
 * codex (`*.node.json`) gives the type and categories, and its compiled
 * source gives the display name, its versions and whether it is a trigger.
 * Hidden (deprecated) nodes are skipped.
 *
 * Needs `tar` on the PATH (Git Bash, macOS and Linux all have it) and network
 * access to registry.npmjs.org. Nothing else; no install.
 */
import { execFileSync } from "node:child_process";
import {
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const FRONTEND_OUT = resolve(here, "../src/app-catalogue.ts");
const BACKEND_OUT = resolve(here, "../../backend/src/nie/n8n-node-catalogue.ts");

const requested = process.argv[2];
const version =
  requested ??
  execFileSync("npm", ["view", "n8n-nodes-base", "version"], {
    encoding: "utf8",
    shell: true,
  }).trim();
const url = `https://registry.npmjs.org/n8n-nodes-base/-/n8n-nodes-base-${version}.tgz`;

const work = mkdtempSync(join(tmpdir(), "naigx-n8n-"));
try {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${String(response.status)}`);
  writeFileSync(
    join(work, "base.tgz"),
    Buffer.from(await response.arrayBuffer()),
  );
  // Relative paths, from inside the temp dir: GNU tar reads a Windows drive
  // letter as a remote host name.
  execFileSync(
    "tar",
    [
      "-xzf",
      "base.tgz",
      "--wildcards",
      "package/dist/nodes/*.node.json",
      "package/dist/nodes/*.node.js",
    ],
    { stdio: "inherit", cwd: work },
  );

  const codexFiles = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      const path = join(dir, entry);
      if (statSync(path).isDirectory()) walk(path);
      else if (entry.endsWith(".node.json")) codexFiles.push(path);
    }
  };
  walk(join(work, "package", "dist", "nodes"));

  const numbers = (text) =>
    text
      .split(",")
      .map((v) => Number(v.trim()))
      .filter((v) => !Number.isNaN(v) && v > 0);

  /** `{ max, min }` — the newest version and the oldest one still shipped. */
  const versionsOf = (text) => {
    const m = /(?:defaultVersion|version):\s*(\[[^\]]*\]|[\d.]+)/.exec(text);
    if (m === null) return { max: 1, min: 1 };
    const raw = m[1];
    if (raw.startsWith("[")) {
      const all = numbers(raw.slice(1, -1));
      return all.length === 0
        ? { max: 1, min: 1 }
        : { max: Math.max(...all), min: Math.min(...all) };
    }
    const max = Number(raw);
    // A versioned node declares `defaultVersion` and lists every version it
    // still ships as the keys of `nodeVersions`.
    const block = /nodeVersions\s*=\s*\{([\s\S]*?)\};/.exec(text)?.[1];
    if (block !== undefined) {
      const keys = [...block.matchAll(/(?:^|[\s,{])["']?(\d+(?:\.\d+)?)["']?\s*:/g)]
        .map((k) => Number(k[1]))
        .filter((v) => !Number.isNaN(v) && v > 0);
      if (keys.length > 0) return { max, min: Math.min(...keys) };
    }
    return { max, min: /defaultVersion/.test(m[0]) ? 1 : max };
  };

  const apps = [];
  for (const codexPath of codexFiles) {
    const codex = JSON.parse(readFileSync(codexPath, "utf8"));
    let source;
    try {
      source = readFileSync(
        codexPath.replace(/\.node\.json$/, ".node.js"),
        "utf8",
      );
    } catch {
      continue;
    }
    if (/hidden:\s*true/.test(source)) continue;
    const name = /displayName:\s*['"]([^'"]+)['"]/.exec(source)?.[1];
    if (name === undefined || typeof codex.node !== "string") continue;
    const group = /group:\s*\[([^\]]*)\]/.exec(source)?.[1] ?? "";
    const { max, min } = versionsOf(source);
    apps.push({
      type: codex.node,
      name,
      categories: Array.isArray(codex.categories)
        ? [...new Set(codex.categories.map((c) => String(c).trim()))]
        : [],
      version: max,
      minVersion: min,
      trigger: /trigger/.test(group),
      docs: codex.resources?.primaryDocumentation?.[0]?.url ?? null,
    });
  }
  apps.sort((a, b) => a.name.localeCompare(b.name));

  const source = `n8n-nodes-base@${version}`;
  const header = `// Generated by frontend/scripts/app-catalogue.mjs — do not edit by hand.\n// Regenerate: node scripts/app-catalogue.mjs [version]\n\n`;

  const frontendBody = JSON.stringify(
    {
      source,
      generated: new Date().toISOString().slice(0, 10),
      apps: apps.map(({ minVersion: _min, ...rest }) => rest),
    },
    null,
    2,
  );
  writeFileSync(
    FRONTEND_OUT,
    `// Generated by scripts/app-catalogue.mjs — do not edit by hand.\n// Regenerate: node scripts/app-catalogue.mjs [version]\n\nexport const APP_CATALOGUE = ${frontendBody} as const;\n`,
  );

  // The backend needs only what the scaffold renderer reads, one node a line.
  const rows = apps
    .map(
      (a) =>
        `  [${JSON.stringify(a.name)}, ${JSON.stringify(a.type)}, ${String(a.minVersion)}, ${String(a.trigger)}],`,
    )
    .join("\n");
  writeFileSync(
    BACKEND_OUT,
    `${header}/** The package this list was read from. */\nexport const N8N_NODE_CATALOGUE_SOURCE = ${JSON.stringify(source)};\n\n/** \`[display name, node type, oldest shipped version, is a trigger]\`. */\n// prettier-ignore\nexport const N8N_NODE_CATALOGUE: readonly (readonly [string, string, number, boolean])[] = [\n${rows}\n];\n`,
  );

  console.log(
    `${String(apps.length)} apps from ${source} → ${FRONTEND_OUT} and ${BACKEND_OUT}`,
  );
} finally {
  rmSync(work, { recursive: true, force: true });
}
