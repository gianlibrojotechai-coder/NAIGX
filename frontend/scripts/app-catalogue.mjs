/**
 * Generates `src/app-catalogue.ts` — every integration n8n ships — from the
 * published `n8n-nodes-base` package (D-94).
 *
 *   node scripts/app-catalogue.mjs            # latest published version
 *   node scripts/app-catalogue.mjs 2.15.1     # a pinned version
 *
 * The catalogue is what the presentation's app picker offers and what the n8n
 * download can actually wire, so it is generated from n8n's own node files
 * rather than typed by hand: each node's codex (`*.node.json`) gives the type
 * and categories, and its compiled source gives the display name, the latest
 * version and whether it is a trigger. Hidden (deprecated) nodes are skipped.
 *
 * Needs `tar` on the PATH (Git Bash, macOS and Linux all have it) and network
 * access to registry.npmjs.org. Nothing else; no install.
 */
import { execFileSync } from "node:child_process";
import {
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, "../src/app-catalogue.ts");

const requested = process.argv[2];
const version =
  requested ??
  execFileSync("npm", ["view", "n8n-nodes-base", "version"], {
    encoding: "utf8",
    shell: true,
  }).trim();
const url = `https://registry.npmjs.org/n8n-nodes-base/-/n8n-nodes-base-${version}.tgz`;

const work = mkdtempSync(join(tmpdir(), "naigx-n8n-"));
try {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${String(response.status)}`);
  writeFileSync(
    join(work, "base.tgz"),
    Buffer.from(await response.arrayBuffer()),
  );
  // Relative paths, from inside the temp dir: GNU tar reads a Windows drive
  // letter as a remote host name.
  execFileSync(
    "tar",
    [
      "-xzf",
      "base.tgz",
      "--wildcards",
      "package/dist/nodes/*.node.json",
      "package/dist/nodes/*.node.js",
    ],
    { stdio: "inherit", cwd: work },
  );

  const codexFiles = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      const path = join(dir, entry);
      if (statSync(path).isDirectory()) walk(path);
      else if (entry.endsWith(".node.json")) codexFiles.push(path);
    }
  };
  walk(join(work, "package", "dist", "nodes"));

  const versionOf = (text) => {
    const m = /(?:defaultVersion|version):\s*(\[[^\]]*\]|[\d.]+)/.exec(text);
    if (m === null) return 1;
    const raw = m[1];
    if (!raw.startsWith("[")) return Number(raw);
    const versions = raw
      .slice(1, -1)
      .split(",")
      .map((v) => Number(v.trim()))
      .filter((v) => !Number.isNaN(v));
    return versions.length === 0 ? 1 : Math.max(...versions);
  };

  const apps = [];
  for (const codexPath of codexFiles) {
    const codex = JSON.parse(readFileSync(codexPath, "utf8"));
    let source;
    try {
      source = readFileSync(
        codexPath.replace(/\.node\.json$/, ".node.js"),
        "utf8",
      );
    } catch {
      continue;
    }
    if (/hidden:\s*true/.test(source)) continue;
    const name = /displayName:\s*['"]([^'"]+)['"]/.exec(source)?.[1];
    if (name === undefined || typeof codex.node !== "string") continue;
    const group = /group:\s*\[([^\]]*)\]/.exec(source)?.[1] ?? "";
    apps.push({
      type: codex.node,
      name,
      categories: Array.isArray(codex.categories)
        ? [...new Set(codex.categories.map((c) => String(c).trim()))]
        : [],
      version: versionOf(source),
      trigger: /trigger/.test(group),
      docs: codex.resources?.primaryDocumentation?.[0]?.url ?? null,
    });
  }
  apps.sort((a, b) => a.name.localeCompare(b.name));

  const body = JSON.stringify(
    {
      source: `n8n-nodes-base@${version}`,
      generated: new Date().toISOString().slice(0, 10),
      apps,
    },
    null,
    2,
  );
  writeFileSync(
    OUT,
    `// Generated by scripts/app-catalogue.mjs — do not edit by hand.\n// Regenerate: node scripts/app-catalogue.mjs [version]\n\nexport const APP_CATALOGUE = ${body} as const;\n`,
  );
  console.log(
    `${String(apps.length)} apps from n8n-nodes-base@${version} → ${OUT}`,
  );
} finally {
  rmSync(work, { recursive: true, force: true });
}
